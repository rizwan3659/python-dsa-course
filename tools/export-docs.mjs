// Generates Markdown documents from the course data, so they never drift from the browser course:
//   docs/interview/top-100.md   the Top 100 roadmap (questions/roadmap.js)
//   curriculum/syllabus.md      every topic with its lessons, visualizers and question counts
// Usage: node tools/export-docs.mjs [--check]
import fs from 'fs';
import path from 'path';
import {loadCourse, root} from './load-course.mjs';

const CHECK = process.argv.includes('--check');
const {C, problems} = loadCourse();
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const DIFF = {1: 'Easy', 2: 'Medium', 3: 'Hard'};
const dir = t => `${String(t.n).padStart(2, '0')}_${t.id}`;
const files = new Map();

// ---- Top 100 ----
{
  const R = C.ROADMAP;
  const track = k => R.tracks.find(t => t.k === k).name;
  const all = R.groups.flatMap(g => g.items);
  let md = `# Top 100 interview roadmap\n\n<!-- generated by tools/export-docs.mjs from questions/roadmap.js: do not edit by hand -->\n\n`;
  md += `100 problems from the course, grouped by pattern. Each problem is available in the browser (Interview page, with your progress) and locally:\n\n\`\`\`bash\npython dsa.py test <id>\n\`\`\`\n\n`;
  md += `## Tracks\n\n| Track | Problems | Description |\n|---|---|---|\n`;
  R.tracks.forEach(t => { md += `| ${t.name} | ${all.filter(([, k]) => k === t.k).length} | ${t.desc} |\n`; });
  md += `\n## Eight-week plan\n\n| Week | Focus |\n|---|---|\n` + R.plan.map(([w, f]) => `| ${w} | ${f} |`).join('\n') + '\n';
  R.groups.forEach(g => {
    md += `\n## ${g.name}\n\n| # | Problem | Id | Difficulty | Track | Topic | Local file |\n|---|---|---|---|---|---|---|\n`;
    g.items.forEach(([id, k]) => {
      const q = C.qmap[id], t = C.tmap[q.topic];
      const n = all.findIndex(([x]) => x === id) + 1;
      md += `| ${n} | ${q.title} | \`${id}\` | ${DIFF[q.d || 1]} | ${track(k)} | ${t.title} | [exercise](../../exercises/${dir(t)}/${id.replace(/-/g, '_')}.py) |\n`;
    });
  });
  md += `\n## How to use it\n\n1. Do the problems of one group in order. Before coding, say the pattern out loud.\n2. If you are stuck for 20 minutes, take one hint, not the solution.\n3. Mark a problem as done only if you can re-solve it from a blank file a few days later.\n4. After each group, do one timed round on the Interview page at the same difficulty.\n`;
  files.set('docs/interview/top-100.md', md);
}

// ---- Syllabus ----
{
  let md = `# Syllabus\n\n<!-- generated by tools/export-docs.mjs from topics/ and questions/: do not edit by hand -->\n\n`;
  const qs = C.questions;
  md += `${C.topics.length} topics · ${C.topics.reduce((s, t) => s + t.learn.length, 0)} lessons · ${qs.length} questions (${qs.filter(q => q.type === 'code').length} coding) · ${C.vizMeta.length} visualizers\n`;
  C.PARTS.forEach(p => {
    md += `\n## Part ${p.k}: ${p.name}\n`;
    p.ids.forEach(id => {
      const t = C.tmap[id];
      const tq = qs.filter(q => q.topic === id);
      const mins = t.learn.reduce((s, l) => s + (l.mins || 0), 0);
      const types = {};
      tq.forEach(q => { const k = C.typeLabel(q); types[k] = (types[k] || 0) + 1; });
      md += `\n### ${t.n}. ${t.title}\n\n${t.goal || t.blurb}\n\n`;
      md += `*About ${mins} minutes of lessons · ${tq.length} questions: ${Object.entries(types).map(([k, v]) => `${v} ${k.toLowerCase()}`).join(', ')}*\n\n`;
      md += `| Lesson | Minutes | You will |\n|---|---|---|\n`;
      t.learn.forEach(l => { md += `| ${l.title} | ${l.mins || ''} | ${(l.does || []).join(', ')} |\n`; });
      const viz = C.vizMeta.filter(v => v.topic === id);
      if (viz.length) md += `\nVisualizers: ${viz.map(v => v.title).join(' · ')}\n`;
    });
  });
  files.set('curriculum/syllabus.md', md);
}

// ---- Instructor guides: one per topic, built from lessons, teacher notes, questions and review tasks ----
{
  const PREREQ = {python: [], bigo: ['python'], thinking: ['python', 'bigo'], arrays: ['python', 'bigo'], strings: ['arrays'],
    hashing: ['arrays', 'strings'], stack: ['arrays'], queue: ['stack'], linkedlist: ['python'], recursion: ['python', 'stack'],
    searching: ['arrays'], sorting: ['arrays', 'recursion'], trees: ['recursion', 'queue'], bst: ['trees', 'searching'],
    heap: ['trees', 'arrays'], trie: ['trees', 'hashing'], graphs: ['queue', 'recursion', 'hashing'], advgraphs: ['graphs', 'heap'],
    greedy: ['sorting', 'heap'], dp: ['recursion', 'arrays'], bits: ['python', 'thinking'], rangeq: ['arrays', 'trees', 'bits'],
    patterns: ['hashing', 'searching', 'graphs', 'greedy', 'dp']};
  const strip = h => String(h || '').replace(/<[^>]+>/g, '').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
  const firstSentence = s => { const t = strip(s); const m = t.match(/^.*?[.!?](\s|$)/); return (m ? m[0] : t).trim(); };
  const link = id => { const q = C.qmap[id]; return q ? `${q.title} (\`${id}\`)` : `\`${id}\``; };
  const blocksOf = t => [...t.learn.flatMap(l => l.blocks || []), ...(t.challenge || []), ...(t.review || [])];
  const index = [];
  C.topics.forEach(t => {
    const name = `${dir(t)}.md`;
    index.push(`| ${t.n} | [${t.title}](${name}) | ${t.learn.reduce((s, l) => s + (l.mins || 0), 0)} min | ${(PREREQ[t.id] || []).map(p => C.tmap[p].title).join(', ') || '—'} |`);
    const tq = C.questions.filter(q => q.topic === t.id);
    const lessonIds = new Set(t.learn.flatMap(l => (l.blocks || []).filter(b => b.t === 'q').flatMap(b => b.ids)));
    const codes = tq.filter(q => q.type === 'code' && !q.build);
    const pick = (d, n, used) => codes.filter(q => (q.d || 1) === d && !used.has(q.id)).sort((a, b) => lessonIds.has(b.id) - lessonIds.has(a.id)).slice(0, n);
    const used = new Set();
    const classEx = pick(1, 3, used); classEx.forEach(q => used.add(q.id));
    const pair = pick(2, 2, used); pair.forEach(q => used.add(q.id));
    const homework = [...pick(2, 2, used), ...pick(3, 1, used)];
    const build = tq.filter(q => q.build);
    const lessonMins = t.learn.reduce((s, l) => s + (l.mins || 0), 0);
    const teacher = t.learn.flatMap(l => (l.blocks || []).filter(b => b.t === 'teacher').flatMap(b => b.items.map(strip)));
    const flash = blocksOf(t).filter(b => b.t === 'flash').flatMap(b => b.items);
    const tasks = blocksOf(t).filter(b => b.t === 'task' && /homework/i.test(b.title || '')).flatMap(b => b.items.map(strip));
    const demos = t.learn.flatMap(l => (l.blocks || []).filter(b => b.t === 'code' && b.title).map(b => `${b.title} (lesson “${l.title}”)`));
    const b2o = (t.challenge || []).filter(b => b.t === 'b2o');
    const viz = C.vizMeta.filter(v => v.topic === t.id);
    const tracing = tq.filter(q => q.type === 'dryrun' || q.type === 'predict').slice(0, 4);
    const debug = tq.filter(q => q.type === 'debug' && q.tests).slice(0, 2);
    let md = `# Instructor guide · Topic ${t.n}: ${t.title}\n\n<!-- generated by tools/export-docs.mjs from topics/ and questions/: do not edit by hand -->\n\n`;
    md += `## Learning objectives\n\n${strip(t.goal || t.blurb)}\n\nBy the end of the topic, students can:\n\n${t.learn.map(l => `- **${l.title}:** ${firstSentence(l.lead)}`).join('\n')}\n\n`;
    md += `## Duration and prerequisites\n\n- Lessons: about **${lessonMins} minutes** of guided material (${t.learn.length} lessons)\n- Practice: ${codes.length} coding problems and ${tq.length - codes.length} quick questions in the bank; plan at least as much practice time as lesson time\n`;
    md += `- Suggested format: ${lessonMins > 75 ? `two 90-minute sessions (split after lesson ${Math.ceil(t.learn.length / 2)})` : 'one 90-minute session'}\n`;
    md += `- Prerequisites: ${(PREREQ[t.id] || []).map(p => `Topic ${C.tmap[p].n} (${C.tmap[p].title})`).join(', ') || 'none'}\n\n`;
    md += `## Lesson plan\n\n| # | Lesson | Minutes | Students will | Show |\n|---|---|---|---|---|\n`;
    t.learn.forEach((l, i) => {
      const shows = (l.blocks || []).filter(b => b.t === 'viz').map(b => (C.vizMeta.find(v => v.name === b.fn) || {title: b.fn}).title);
      md += `| ${i + 1} | ${l.title} | ${l.mins || ''} | ${(l.does || []).join(', ')} | ${shows.join('; ') || '—'} |\n`;
    });
    md += `\nOpen the topic in the browser (\`#t/${t.id}\`) and project it; every lesson alternates a short explanation with questions the class answers together.\n\n`;
    md += `## Live coding demonstrations\n\n`;
    md += demos.length ? demos.map(d => `- ${d}`).join('\n') + '\n' : '- Code the first “Code it” problem of each lesson live, thinking aloud.\n';
    b2o.forEach(b => { md += `- Brute force → optimal walkthrough: **${strip(b.title)}** (Challenge tab). Code the brute force, ask students to find the repeated work, then refactor.\n`; });
    if (viz.length) md += `- Visualizers to drive while students predict the next step: ${viz.map(v => v.title).join(' · ')}\n`;
    md += `\n## Questions to ask the class\n\nAsk, wait for several answers, then reveal (the answers are on the topic's Review flashcards).\n\n`;
    md += flash.slice(0, 8).map(([q]) => `- ${strip(q)}`).join('\n') + '\n';
    if (teacher.length) md += `\n### Teaching notes\n\n${teacher.map(x => `- ${x}`).join('\n')}\n`;
    md += `\n## Classroom exercises (individual, 10–15 minutes each)\n\n${classEx.length ? classEx.map(q => `- ${link(q.id)}`).join('\n') : '- Use the lesson questions.'}\n`;
    if (tracing.length) md += `\nCode tracing on the board: ${tracing.map(q => link(q.id)).join(', ')}\n`;
    if (debug.length) md += `\nFind-the-bug warm-ups: ${debug.map(q => link(q.id)).join(', ')}\n`;
    md += `\n## Pair programming (25–30 minutes)\n\nOne driver types, one navigator thinks ahead and checks edge cases; swap every 10 minutes.\n\n`;
    md += pair.length ? pair.map(q => `- ${link(q.id)}`).join('\n') + '\n' : '- Pick a medium problem from the Practice page for this topic.\n';
    if (build.length) md += `- Build from scratch: ${build.map(q => link(q.id)).join(', ')}\n`;
    md += `\n## Homework\n\n`;
    md += homework.map(q => `- ${link(q.id)}`).join('\n') + (homework.length ? '\n' : '');
    md += tasks.map(x => `- ${x}`).join('\n') + (tasks.length ? '\n' : '');
    md += `- Finish the topic's Review quiz in the browser and clear the revision queue.\n\n`;
    md += `## Solutions and grading\n\n- Reference solutions: \`solutions/${dir(t)}/\` (also behind “Show solution” in the browser).\n- Students check their own work with \`python dsa.py test <id>\`; collect \`pytest tests/test_my_solutions.py -k ${t.id}\` output as evidence.\n- Grade with the coding rubric in [README.md](README.md#grading-rubrics).\n`;
    files.set(`docs/instructor/${name}`, md);
  });
  files.set('docs/instructor/topics.md', `# Instructor guides by topic\n\n<!-- generated by tools/export-docs.mjs: do not edit by hand -->\n\n| # | Topic | Lesson time | Prerequisites |\n|---|---|---|---|\n${index.join('\n')}\n`);
}

let stale = 0;
for (const [rel, content] of files) {
  const f = path.join(root, rel);
  const old = fs.existsSync(f) ? fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n') : null;
  if (old === content) continue;
  stale++;
  if (!CHECK) { fs.mkdirSync(path.dirname(f), {recursive: true}); fs.writeFileSync(f, content); console.log('wrote', rel); }
  else console.log('out of date:', rel);
}
if (CHECK && stale) { console.log('Run: node tools/export-docs.mjs'); process.exit(1); }
if (!stale) console.log('Generated docs are up to date.');
